#!/usr/bin/env python3
"""
build_single_file.py -- flatten the QIUP digital-twin package into ONE file.

Source of truth = the modular ``*.py`` sources listed in ``MODULES``.
This script concatenates them (in dependency order) into
``qiup_digital_twin_full.py``. DO NOT hand-edit the generated file -- edit the
modules and re-run this. (Like exporting a PDF from a .docx.)

Comment 2.3 required workflow (never edit qiup_digital_twin_full.py by hand):

    modify modular source
           ↓
    run tests
           ↓
    run build_single_file.py
           ↓
    generate qiup_digital_twin_full.py
           ↓
    run parity tests

CFG-P0 single-file release (comment 2):
  * ``provenance`` is an internal module and MUST be inlined.
  * A clean rebuild must reproduce the distributed file byte-for-byte.
  * SHA-256 of every modular source, this build script, and the generated
    file are calculated/stored by ``provenance`` into
    ``configs/single_file_build_hashes.json`` (comment 2.4).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from provenance import (
    CALIBRATION_STATUS,
    PACKAGE_VERSION,
    RELEASE_CLASSIFICATION,
    SINGLE_FILE_BUILD_HASH_RELATIVE,
    compute_single_file_build_hashes,
    hash_text_normalized,
    verify_single_file_build_hashes,
    write_single_file_build_hashes,
)

# Dependency order (imports flow downward; later modules may import earlier).
# provenance has no internal deps and is required by simulate (and lazily by
# setup_params); place it immediately before simulate.
MODULES = [
    "setup_params",
    "latents",
    "optics",
    "detector",
    "provenance",
    "simulate",
]
MODULE_FILES = {m: f"{m}.py" for m in MODULES}
# Names whose ``from X import …`` / ``import X`` lines are stripped during
# single-file construction (resolved in-process, not as external packages).
# Comment 2.2: ``provenance`` MUST be here so ``from provenance import …``
# does not survive into ``qiup_digital_twin_full.py``.
INTERNAL = frozenset(
    {
        "setup_params",
        "latents",
        "optics",
        "detector",
        "provenance",
        "simulate",
    }
)
if INTERNAL != frozenset(MODULES):
    raise RuntimeError(
        "INTERNAL must match MODULES exactly "
        f"(INTERNAL={sorted(INTERNAL)}, MODULES={MODULES})"
    )
OUT = "qiup_digital_twin_full.py"
HASH_RELATIVE = SINGLE_FILE_BUILD_HASH_RELATIVE
BUILD_SCRIPT_NAME = "build_single_file.py"


def strip_module(text: str, is_first: bool) -> str:
    lines = text.split("\n")
    out, i, n = [], 0, len(lines)
    # drop leading module docstring
    while i < n and lines[i].strip() == "":
        i += 1
    if i < n and (lines[i].lstrip().startswith('"""') or lines[i].lstrip().startswith("'''")):
        q = lines[i].lstrip()[:3]
        # single-line docstring?
        if lines[i].count(q) >= 2 and len(lines[i].strip()) > 3:
            i += 1
        else:
            i += 1
            while i < n and q not in lines[i]:
                i += 1
            i += 1  # closing line
    while i < n:
        line = lines[i]
        s = line.strip()
        # drop __future__ (added once at top) and inter-module imports
        if s.startswith("from __future__ import"):
            i += 1
            continue
        drop = False
        for mod in INTERNAL:
            if s.startswith(f"from {mod} import") or s.startswith(f"import {mod}"):
                drop = True
                if "(" in s and ")" not in s:  # multi-line import block
                    while i < n and ")" not in lines[i]:
                        i += 1
                break
        if drop:
            i += 1
            continue
        out.append(line)
        i += 1
    return "\n".join(out).strip("\n")


def render_single_file(here: Path) -> str:
    """Return the exact UTF-8 text that must be written to ``OUT`` (LF newlines)."""
    parts = [
        '"""',
        f"QIUP SIMULATOR v{PACKAGE_VERSION} -- single-file build "
        "(generated by build_single_file.py).",
        f"Classification: {RELEASE_CLASSIFICATION}. "
        f"Calibration status: {CALIBRATION_STATUS}.",
        f"Self-contained copy of the {len(MODULES)}-module package "
        f"({', '.join(MODULES)}).",
        "DO NOT HAND-EDIT THIS FILE.",
        "Workflow: edit modular sources → run tests → python build_single_file.py "
        "→ run parity tests.",
        "Sections below map 1:1 to the source modules.",
        '"""',
        "from __future__ import annotations",
        "",
    ]
    for m in MODULES:
        text = (here / MODULE_FILES[m]).read_text(encoding="utf-8")
        body = strip_module(text, is_first=(m == MODULES[0]))
        parts.append(
            f"\n# {'#' * 76}\n# ==== MODULE: {m} "
            f"{'=' * (60 - len(m))}\n# {'#' * 76}\n"
        )
        parts.append(body)
    return "\n".join(parts).rstrip() + "\n"


def build_hash_manifest(here: Path, generated_text: str) -> dict:
    """Delegate Comment-2.4 hashing to ``provenance`` (SoT for build hashes)."""
    return compute_single_file_build_hashes(here, generated_text=generated_text)


def write_outputs(here: Path, *, check_only: bool = False) -> int:
    generated = render_single_file(here)
    out_path = here / OUT
    hash_path = here / HASH_RELATIVE
    manifest = build_hash_manifest(here, generated)

    if check_only:
        if not out_path.is_file():
            print(f"MISSING {OUT}", file=sys.stderr)
            return 1
        live = out_path.read_text(encoding="utf-8").replace("\r\n", "\n").replace("\r", "\n")
        if live != generated:
            print(
                f"STALE {OUT}: rebuild differs from distributed file "
                f"(live_sha={hash_text_normalized(live)} "
                f"expected_sha={manifest['generated_file_sha256']})",
                file=sys.stderr,
            )
            return 1
        if not hash_path.is_file():
            print(f"MISSING {HASH_RELATIVE}", file=sys.stderr)
            return 1
        try:
            verify_single_file_build_hashes(here, generated_text=generated)
        except ValueError as exc:
            print(str(exc), file=sys.stderr)
            return 1
        print(f"OK {OUT} matches clean rebuild ({manifest['generated_line_count']} lines)")
        return 0

    out_path.write_text(generated, encoding="utf-8", newline="\n")
    # Recompute after writing so on-disk generated file is part of the fixture.
    manifest = compute_single_file_build_hashes(here, generated_text=generated)
    write_single_file_build_hashes(manifest, here)
    print(
        f"wrote {OUT}: {manifest['generated_line_count']} lines "
        f"(sha256={manifest['generated_file_sha256'][:16]}…)"
    )
    print(f"wrote {HASH_RELATIVE}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 0 iff distributed single-file matches a clean in-memory rebuild.",
    )
    args = parser.parse_args(argv)
    here = Path(__file__).resolve().parent
    missing = [MODULE_FILES[m] for m in MODULES if not (here / MODULE_FILES[m]).is_file()]
    if missing:
        print(f"missing modular sources: {', '.join(missing)}", file=sys.stderr)
        return 1
    return write_outputs(here, check_only=bool(args.check))


if __name__ == "__main__":
    raise SystemExit(main())
